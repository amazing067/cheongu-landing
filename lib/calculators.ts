export function findCalculator(slug: string): CalcDef | undefined {
  return calculators.find((c) => c.slug === slug);
}

export function calcPath(slug: string): string {
  return `/calc/${encodeURIComponent(slug)}`;
}

export function calcUrl(slug: string): string {
  return `${SITE_URL}${calcPath(slug)}`;
}
